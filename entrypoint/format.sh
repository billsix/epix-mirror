#!/usr/bin/env bash
# format.sh -- format the whole tree in place. Run via `make format`, and
# automatically when you `exit` a `make shell` (the hook in dotfiles/.extrabashrc).
# Runs in the container or on the host from the repo root.
#
#   C++    : clang-format (.clang-format, google style). Applied tree-wide,
#            INCLUDING the upstream libepix sources -- the maintainer granted an
#            explicit exception to the mirror-preservation rule for formatting.
#   Python : ruff lint-fix + format (config in python/pyproject.toml).
#
# The generated umbrella header epix.h is skipped (it's regenerated by make_header).
#
# Every step runs (one pass reports all the red), but the script exits nonzero if
# ANY step failed -- a plain sequence would report only the last command's status.
export VIRTUAL_ENV_DISABLE_PROMPT=1
[ -f /venv/bin/activate ] && source /venv/bin/activate
[ -d /epix ] && cd /epix

status=0

echo "clang-format (C++) ..."
find src include/epix python/epix build-aux \
     \( -name '*.cc' -o -name '*.h' \) ! -name 'epix.h' -print0 \
    | xargs -0 -r clang-format -i || status=1

echo "ruff (Python) ..."
RUFF_CFG=python/pyproject.toml
ruff check --fix --config "$RUFF_CFG" . || status=1
ruff format --config "$RUFF_CFG" . || status=1

exit $status
